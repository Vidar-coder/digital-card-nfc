/**
 * Concatenates every .gs file into apps-script/dist/Code.gs for one-paste
 * installation:  node apps-script/tools/bundle.mjs
 * (Using the separate files — or clasp — works identically.)
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIRST = ["Config.gs", "Utils.gs", "Validation.gs", "Database.gs"];
const files = [...FIRST, ...readdirSync(src).filter((f) => f.endsWith(".gs") && !FIRST.includes(f)).sort()];

const banner = `/**
 * NFC Digital Card — Google Apps Script backend (bundled ${files.length} files).
 * Generated by apps-script/tools/bundle.mjs — edit the source files, not this one.
 * Install: Extensions → Apps Script → paste into Code.gs → run setupDatabase().
 */\n\n`;

const body = files
  .map((f) => `// ${"=".repeat(74)}\n// ${f}\n// ${"=".repeat(74)}\n${readFileSync(join(src, f), "utf8").trim()}\n`)
  .join("\n");

mkdirSync(join(src, "dist"), { recursive: true });
writeFileSync(join(src, "dist", "Code.gs"), banner + body);
console.log(`Wrote apps-script/dist/Code.gs (${files.length} files, ${(body.length / 1024).toFixed(1)} KB)`);
